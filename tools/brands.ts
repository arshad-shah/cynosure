/**
 * Generates `src/brands/*` from Simple Icons data: `node --import tsx tools/brands.ts <path to simple-icons package>`.
 * Brand marks are copied exactly (path, colour, guidelines link), never redrawn: brands allow their marks to be used
 * only as they publish them. The list is `tools/brands.json`; brands that asked Simple Icons to remove their mark are
 * listed there with their own brand kit instead, and are not generated.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkg = process.argv[2];
if (!pkg) throw new Error("Usage: tools/brands.ts <path to an unpacked simple-icons package>");
const list = JSON.parse(readFileSync("tools/brands.json", "utf8")) as { slugs: string[] };
const data = JSON.parse(readFileSync(join(pkg, "data/simple-icons.json"), "utf8")) as {
  title: string;
  slug?: string;
  hex: string;
  source: string;
  guidelines?: string;
}[];
const version = (JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")) as { version: string }).version;
const bySlug = new Map(data.map((d) => [d.slug as string, d]));
const camel = (slug: string) => slug.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

const out = "src/brands";
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const exports: string[] = [];
for (const slug of list.slugs) {
  const d = bySlug.get(slug);
  if (!d) throw new Error(`Simple Icons has no "${slug}"`);
  const svg = readFileSync(join(pkg, "icons", `${slug}.svg`), "utf8");
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!path) throw new Error(`No path in ${slug}.svg`);
  const brand = {
    title: d.title,
    hex: d.hex,
    ...(d.guidelines ? { guidelines: d.guidelines } : {}),
    source: d.source,
  };
  writeFileSync(
    join(out, `${slug}.ts`),
    `// Generated by tools/brands.ts from Simple Icons ${version}. Do not edit: the mark is the brand's own.\n` +
      `import type { IconData } from "../icons/types.js";\n\n` +
      `export const ${camel(slug)}: IconData = ${JSON.stringify({ name: slug, category: "brands", fill: true, brand, body: [["path", { d: path }]] }, null, 2)};\n`,
  );
  exports.push(`export { ${camel(slug)} } from "./${slug}.js";`);
}
writeFileSync(
  join(out, "index.ts"),
  `// Generated by tools/brands.ts from Simple Icons ${version}. Brand marks belong to their owners; see the README.\n${exports.join("\n")}\n`,
);
console.log(`${list.slugs.length} brand marks written to ${out}`);
